#!/usr/bin/env python3
"""Generate the Lean proof that a straight-line ctrBlocksNAsm meets the contract.

Usage: gen_proof.py <program.lean> <namespace> <program-name> <N> <theorem-prefix> <out.lean>

The program file is the output of gen_program.py. For each nr in {10, 12, 14}
the generator follows the code's control flow (the only branches are the
`cmp x9, #12; b.lt; b.eq` dispatch on nr), and emits a proof that runs the
code in LNSym with `sym_n`, resolving each branch from the known nr, and then
proves every field of `Post`. The generator only proposes text: Lean checks
the generated proofs against the generated statements, which still need review.
"""
import re
import sys


def parse_program(path):
    insts = []
    for line in open(path):
        m = re.match(r"\s*\[?\((0x[0-9a-f]+)#64, (0x[0-9a-f]+)#32\)[,\]]*\s*--\s*(.*?)\s*\|", line)
        if m:
            insts.append((int(m.group(1), 16), int(m.group(2), 16), m.group(3).strip()))
    return insts


def sext(v, bits):
    return v - (1 << bits) if v & (1 << (bits - 1)) else v


COND = {0x0: "eq", 0x1: "ne", 0xb: "lt", 0xa: "ge", 0xc: "gt", 0xd: "le"}


def trace(insts, nr):
    """Concrete control flow for one nr: list of (step, addr, branch_target_or_None)."""
    code = {a: (w, t) for a, w, t in insts}
    pc, steps, cmp = 0, [], None
    while True:
        w, t = code[pc]
        op = t.split()[0]
        nxt = pc + 4
        br = None
        if op == "cmp":
            m = re.match(r"cmp x9, #(0x[0-9a-f]+|\d+)$", t)
            assert m, t
            cmp = nr - int(m.group(1), 0)
        elif op.startswith("b."):
            assert (w >> 24) == 0x54, t
            cond = COND[w & 0xf]
            target = pc + sext((w >> 5) & 0x7ffff, 19) * 4
            taken = {"eq": cmp == 0, "ne": cmp != 0, "lt": cmp < 0, "ge": cmp >= 0,
                     "gt": cmp > 0, "le": cmp <= 0}[cond]
            nxt = target if taken else pc + 4
            br = nxt
        steps.append((pc, br))
        if op == "ret":
            return steps
        pc = nxt


def glue(prog, k, addr, nxt):
    """Step k (from state s{k-1}) is a conditional branch to `nxt`."""
    p, s = f"s{k-1}", f"s{k}"
    return f"""  init_next_step h_run stepi_{p} {s}
  have h_step_{k} : {s} = w .PC 0x{nxt:x}#64 {p} := by
    have h := stepi_{p}.symm.trans
      ({prog}.stepi_eq_0x{addr:x} h_{p}_program h_{p}_pc h_{p}_err)
    sym_aggregate at h
    exact h
  have h_{s}_program : {s}.program = {prog} := by rw [h_step_{k}, w_program, h_{p}_program]
  have h_{s}_pc : r .PC {s} = 0x{nxt:x}#64 := by rw [h_step_{k}, r_of_w_same]
  have h_{s}_err : r .ERR {s} = .None := by rw [h_step_{k}, r_of_w_different (by decide), h_{p}_err]
  have h_{s}_sp_aligned : CheckSPAlignment {s} := by
    simp only [CheckSPAlignment, read_gpr, h_step_{k},
      r_of_w_different (show StateField.GPR 31#5 ≠ StateField.PC by decide)]
    exact h_{p}_sp_aligned
  have h_{s}_non_effects : ∀ (f : StateField), f ≠ StateField.PC → r f {s} = r f {p} := by
    intro f hf; rw [h_step_{k}, r_of_w_different hf]
  have h_{s}_memory_effects : {s}.mem = {p}.mem := by rw [h_step_{k}]; exact mem_w_of_mem_eq rfl _ _
  clear h_step_{k} stepi_{p}
"""


def main():
    prog_path, ns, prog, N, thm, out_path = sys.argv[1:7]
    N = int(N)
    insts = parse_program(prog_path)
    mod = prog_path.split("lean/")[-1].removesuffix(".lean").replace("/", ".")
    L = []
    L.append("/- Generated by tools/gen_proof.py; do not edit. -/")
    L.append("import Tactics.Sym")
    L.append("import Tactics.StepThms")
    L.append("import Tactics.Aggregate")
    L.append("import AesCtr.ProofLib")
    L.append(f"import {mod}")
    L.append("")
    L.append(f"namespace {ns}")
    L.append("open AesCtr")
    L.append("")
    L.append("set_option maxRecDepth 100000")
    L.append("set_option maxHeartbeats 0")
    L.append("set_option linter.unusedVariables false")
    L.append("")
    L.append(f"#genStepEqTheorems {prog}")
    L.append("")
    counts = {}
    for nr in (10, 12, 14):
        steps = trace(insts, nr)
        T = len(steps)
        counts[nr] = T
        L.append(f"theorem {thm}_nr{nr} (s0 : ArmState) (h : Pre {prog} 6 (callN s0 {N}) s0)")
        L.append(f"    (h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = {nr}#64) :")
        L.append(f"    Post (callN s0 {N}) s0 (run {T} s0) := by")
        L.append("  obtain ⟨h_s0_program, h_s0_pc, h_s0_err, h_s0_sp_aligned, -, h_args, h_keys, h_srcdst⟩ := h")
        L.append("  simp only [callN, arg, Memory.State.read_mem_bytes_eq_mem_read_bytes, Nat.reduceMul,")
        L.append("    Nat.reduceAdd, BitVec.ofNat_eq_ofNat] at h_args h_keys h_srcdst")
        L.append("  obtain ⟨-, h_dst_legal, -⟩ := h_args.omega_def")
        L.append(f"  have h_nr_mem : Memory.read_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0.mem = {nr}#64 := by")
        L.append("    rw [← Memory.State.read_mem_bytes_eq_mem_read_bytes]; exact h_nr")
        L.append(f"  generalize h_run' : run {T} s0 = sf")
        L.append(f"  have h_run : sf = run {T} s0 := h_run'.symm")
        L.append("  clear h_run'")
        # Segments between branches.
        seg_start = 0  # step index (0-based) where the current segment starts
        state = 0      # state number the segment starts from
        for i, (addr, br) in enumerate(steps):
            if br is not None:
                n = i - seg_start
                if n > 0:
                    L.append(f"  sym_n {n}" + (f" at s{state}" if state else ""))
                L.append(glue(prog, i + 1, addr, br).rstrip("\n"))
                seg_start = i + 1
                state = i + 1
        n = T - seg_start
        if n > 0:
            L.append(f"  sym_n {n}" + (f" at s{state}" if state else ""))
        memfx = ", ".join(f"h_s{k}_memory_effects" for k in range(T, 0, -1))
        L.append(f"""  -- The final state is s{T}.
  refine ⟨h_s{T}_err, ?_, ?_, ?_, ?_⟩
  · sym_aggregate
  · refine ⟨?_, ?_, ?_, ?_, ?_⟩ <;> sym_aggregate
  · intro i hi
    simp only [callN] at hi
    have : {" ∨ ".join(f"i = {j}" for j in range(N))} := by omega
    rcases this with {" | ".join("rfl" for _ in range(N))}
    all_goals
      simp only [callN, block, arg, Memory.State.read_mem_bytes_eq_mem_read_bytes, Nat.reduceMul,
        Nat.reduceAdd, BitVec.ofNat_eq_ofNat, BitVec.add_zero]
      sym_aggregate
      simp only [write_mem_bytes_mem, Memory.State.read_mem_bytes_eq_mem_read_bytes, {memfx}]
      sym_aggregate
      try simp only [Memory.State.read_mem_bytes_eq_mem_read_bytes, {memfx}]
      simp (disch := no_recover mem_tac) only [rd16_write_same, rd_write_sep, BitVec.add_assoc, BitVec.reduceAdd]
      simp only [keystream, h_nr_mem, BitVec.toNat_ofNat, Nat.reducePow, Nat.reduceMod]
      rw [ctrN_eq]
      simp only [aesEncrypt, aesState, block, ctrN, stepCtr, counterBlock_append, subBytes_shiftRows,
        partInstall_lo_hi, rev_vector_64, SubBytes, ShiftRows, MixColumns, BitVec.ofNat_eq_ofNat,
        fst_AddWithCarry_eq_add,
        BitVec.add_zero, Nat.reduceMul, Nat.reduceAdd, Nat.reduceSub, BitVec.add_assoc,
        BitVec.reduceAdd, Memory.State.read_mem_bytes_eq_mem_read_bytes]
      rw [xor_final]
  · intro a n hsep
    simp only [callN, arg, Memory.State.read_mem_bytes_eq_mem_read_bytes, Nat.reduceMul,
      Nat.reduceAdd, BitVec.ofNat_eq_ofNat] at hsep ⊢
    obtain ⟨h_a_legal, -, h_a_sep⟩ := hsep.omega_def
    sym_aggregate
    simp only [write_mem_bytes_mem, Memory.State.read_mem_bytes_eq_mem_read_bytes, {memfx}]
    sym_aggregate
    try simp only [Memory.State.read_mem_bytes_eq_mem_read_bytes, {memfx}]
    simp (disch := no_recover mem_tac) only [rd_write_sep, BitVec.add_assoc, BitVec.reduceAdd]
""")
    # The combined theorem.
    L.append(f"/-- Steps `{prog}` takes for each number of rounds. -/")
    L.append(f"def {thm}Steps (nr : Nat) : Nat :=")
    L.append(f"  if nr = 10 then {counts[10]} else if nr = 12 then {counts[12]} else {counts[14]}")
    L.append("")
    L.append(f"theorem {thm}_correct (s0 : ArmState) (h : Pre {prog} 6 (callN s0 {N}) s0) :")
    L.append(f"    Post (callN s0 {N}) s0 (run ({thm}Steps (callN s0 {N}).nr) s0) := by")
    L.append("  rcases h.nr with hnr | hnr | hnr")
    for nr in (10, 12, 14):
        L.append(f"  · rw [hnr]")
        L.append(f"    have h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = {nr}#64 := by")
        L.append(f"      apply BitVec.eq_of_toNat_eq; simpa [callN, arg] using hnr")
        L.append(f"    exact {thm}_nr{nr} s0 h h_nr")
    L.append("")
    L.append(f"end {ns}")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{out_path}: steps {counts}")


if __name__ == "__main__":
    main()
