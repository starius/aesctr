#!/usr/bin/env python3
"""Generate the top of the bulk function's proof: tails, main theorems.

Usage: gen_bulk_main.py <program.lean> <ns> <prog> <layout> <prefix> <out.lean>

Uses the structure analysis of gen_bulk_ctl.py. For each nr: one lemma per
remainder r < 12 chaining the tail tests and chunk lemmas, and the main
theorem: prologue, loop entry, `loop_compose`, tail, return. Then the final
theorem for all three key sizes. The text is only a proposal; Lean checks it.
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from gen_bulk_ctl import parse_program, analyse  # noqa: E402

G = 12


def side(c="c"):
    return (f"h_nowrap h_dst h_src h_src_legal")


def tail_lemma(P, layout, nr, sec, lens, r):
    tail, ret = sec["tail"], sec["ret"]
    pieces = []
    L = []
    a = L.append
    a(f"""
theorem {P}_tail{nr}_r{r} {{s0 s : ArmState}} {{c : Call}} {{m : Nat}} {{x : BitVec 64}}
    (hg : GroupPost {layout} s0 c m 0x{tail:x}#64 x s) (hr : arg s0 5 = {r}#64) (h_nr : c.nr = {nr})
    (h_fit : m + {r} ≤ c.nblocks) (h_nowrap : c.ivlo.toNat + c.nblocks ≤ 2 ^ 64)
    (h_dst : c.dst.toNat + 16 * c.nblocks ≤ 2 ^ 64)
    (h_src : c.src.toNat = c.dst.toNat ∨ c.src.toNat + 16 * c.nblocks ≤ c.dst.toNat ∨
      c.dst.toNat + 16 * c.nblocks ≤ c.src.toNat)
    (h_src_legal : c.src.toNat + 16 * c.nblocks ≤ 2 ^ 64) :
    GroupPost {layout} s0 c (m + {r}) 0x{ret:x}#64 x (run (EXPR) s) := by""")
    h = "hg"
    k = 0
    done = 0
    for (b, A_and, A_chunk, skip) in sec["tests"]:
        k += 1
        a(f"  have h{k} := {P}_test{nr}_{b} {h}")
        pieces.append("2")
        if r & b:
            a(f"  rw [hr, if_neg (by decide)] at h{k}")
            h = f"h{k}"
            k += 1
            a(f"  have h{k} := {P}_chunk{nr}_{b} s0 _ _ c (m + {done}) {h}.inv h_nr {h}.pc (by omega) "
              f"h_nowrap h_dst h_src h_src_legal rfl")
            a(f"  rw [{h}.x13] at h{k}")
            pieces.append(str(lens["chunk"][b]))
            done += b
        else:
            a(f"  rw [hr, if_pos (by decide)] at h{k}")
        h = f"h{k}"
    expr = pieces[0]
    for p in pieces[1:]:
        expr = f"({expr}) + {p}"
    if r > 0:  # for r = 0 no chunk ran: the fact is about m, which is m + 0 by definition
        a(f"  have e : m + {done} = m + {r} := by omega")
        a(f"  rw [e] at {h}")
    a("  simp only [run_plus]")
    a(f"  exact {h}")
    return "\n".join(L).replace("EXPR", expr), expr


def main():
    prog_path, ns, prog, layout, P, out_path = sys.argv[1:7]
    insts = parse_program(prog_path)
    A = analyse(insts)
    mod = prog_path.split("lean/")[-1].removesuffix(".lean").replace("/", ".")
    moddir = mod.rsplit(".", 1)[0]
    Pc = P[0].upper() + P[1:]
    imports = [f"import {mod}Ctl", "import AesCtr.Compose"]
    lensall = {}
    for nr, sec in A["secs"].items():
        lens = dict(loop=(sec["sub"] - sec["loop"]) // 4, pro=None,
                    chunk={b: (skip - A_chunk) // 4 for (b, _, A_chunk, skip) in sec["tests"]})
        lensall[nr] = lens
        imports.append(f"import {moddir}.G{Pc}Loop{nr}")
        for b in (8, 4, 2, 1):
            imports.append(f"import {moddir}.G{Pc}Chunk{nr}{b}")
    L = ["/- Generated by tools/gen_bulk_main.py; do not edit. -/"] + imports + [
        "", f"namespace {ns}", "open AesCtr", "",
        "set_option maxRecDepth 100000", "set_option maxHeartbeats 0",
        "set_option linter.unusedVariables false"]
    pro = {10: A["blt"] // 4 + 1 + len(A["secs"][10]["keys"]),
           12: A["blt"] // 4 + 2 + len(A["secs"][12]["keys"]),
           14: A["blt"] // 4 + 2 + len(A["secs"][14]["keys"])}
    stepdefs = {}
    for nr in (10, 12, 14):
        sec, lens = A["secs"][nr], lensall[nr]
        exprs = []
        for r in range(G):
            text, expr = tail_lemma(P, layout, nr, sec, lens, r)
            L.append(text)
            exprs.append(expr)
        cases = "\n".join(f"  | {r} => {e}" for r, e in enumerate(exprs))
        L.append(f"""
/-- Steps of the tail for `r` remaining blocks (nr = {nr}). -/
def {P}Tail{nr} : Nat → Nat
{cases}
  | _ => 0""")
        BL = lens["loop"]
        stepdefs[nr] = f"(({pro[nr]} + 1) + n * ({BL} + 2)) + {P}Tail{nr} r + 1"
        rcases = " | ".join("rfl" for _ in range(G))
        rcond = " ∨ ".join(f"rv = {r}" for r in range(G))
        per_r = []
        for r in range(G):
            per_r.append(f"""  · rw [show {P}Tail{nr} {r} = {exprs[r]} from rfl]
    have ht := {P}_tail{nr}_r{r} hloop (by rw [hr']) h_nr' (by simp only [callBulk]; omega)
      h_nowrap h_dst h_src h_src_legal
    rw [show 12 * (arg s0 4).toNat + {r} = (callBulk {G} s0).nblocks by simp only [callBulk]; omega] at ht
    exact {P}_ret{nr} ht""")
        L.append(f"""
theorem {P}_main{nr} (s0 : ArmState) (h : Pre {prog} 8 (callBulk {G} s0) s0)
    (h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = {nr}#64)
    (h_r : (arg s0 5).toNat < {G})
    (h_nowrap : (callBulk {G} s0).ivlo.toNat + (callBulk {G} s0).nblocks ≤ 2 ^ 64) :
    Post (callBulk {G} s0) s0
      (run ((({pro[nr]} + 1) + (arg s0 4).toNat * ({BL} + 2)) + {P}Tail{nr} (arg s0 5).toNat + 1) s0) := by
  have h_nr' : (callBulk {G} s0).nr = {nr} := by
    simp only [callBulk, arg, Nat.reduceMul, Nat.reduceAdd, BitVec.ofNat_eq_ofNat, h_nr]; rfl
  have h_dst : (callBulk {G} s0).dst.toNat + 16 * (callBulk {G} s0).nblocks ≤ 2 ^ 64 := h.args_dst.hb
  have h_src : (callBulk {G} s0).src.toNat = (callBulk {G} s0).dst.toNat ∨
      (callBulk {G} s0).src.toNat + 16 * (callBulk {G} s0).nblocks ≤ (callBulk {G} s0).dst.toNat ∨
      (callBulk {G} s0).dst.toNat + 16 * (callBulk {G} s0).nblocks ≤ (callBulk {G} s0).src.toNat := by
    rcases h.src_dst with ⟨he, -⟩ | hs
    · left; rw [he]
    · right; have := hs.omega_def; omega
  have h_src_legal : (callBulk {G} s0).src.toNat + 16 * (callBulk {G} s0).nblocks ≤ 2 ^ 64 := by
    rcases h.src_dst with ⟨he, hl⟩ | hs
    · rw [he]; exact hl
    · exact hs.ha
  rw [run_plus, run_plus, run_plus, run_plus]
  have hp := {P}_pro{nr} s0 _ h h_nr rfl
  have hz := {P}_cbz{nr} hp
  have hx : arg s0 4 = BitVec.ofNat 64 (arg s0 4).toNat := by simp
  rw [hx] at hz
  have hloop := loop_compose (arg s0 4).toNat (arg s0 4).isLt {BL}
    0x{A['secs'][nr]['loop']:x}#64 0x{A['secs'][nr]['tail']:x}#64 0x{A['secs'][nr]['sub']:x}#64
    (fun s m hinv hpc hfit => {P}_loop{nr} s0 s _ _ m hinv h_nr' hpc hfit h_nowrap h_dst h_src h_src_legal rfl)
    (fun s m x hg => {P}_back{nr} hg) (by simp only [callBulk]; omega) _ hz
  have hr' : arg s0 5 = BitVec.ofNat 64 (arg s0 5).toNat := by simp
  generalize hrv : (arg s0 5).toNat = rv at h_r hr'
  have : {rcond} := by omega
  rcases this with {rcases}
{chr(10).join(per_r)}""")
    L.append(f"""
/-- Steps the bulk function takes for `n` groups and `r` more blocks. -/
def {P}Steps (nr n r : Nat) : Nat :=
  if nr = 10 then {stepdefs[10]} else if nr = 12 then {stepdefs[12]} else {stepdefs[14]}

/-- The bulk function meets the contract: for any number of groups `n` and any
remainder `r < 12`, as long as the low 64 bits of the counter do not wrap. -/
theorem {P}_correct (s0 : ArmState) (h : Pre {prog} 8 (callBulk {G} s0) s0)
    (h_r : (arg s0 5).toNat < {G})
    (h_nowrap : (callBulk {G} s0).ivlo.toNat + (callBulk {G} s0).nblocks ≤ 2 ^ 64) :
    Post (callBulk {G} s0) s0
      (run ({P}Steps (callBulk {G} s0).nr (arg s0 4).toNat (arg s0 5).toNat) s0) := by
  rcases h.nr with hnr | hnr | hnr
  all_goals
    rw [hnr]
    simp only [{P}Steps, show (10 : Nat) = 10 from rfl, show (12 : Nat) = 12 from rfl,
      show (14 : Nat) = 14 from rfl]
  · have h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = 10#64 := by
      apply BitVec.eq_of_toNat_eq; simpa [callBulk, arg] using hnr
    exact {P}_main10 s0 h h_nr h_r h_nowrap
  · have h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = 12#64 := by
      apply BitVec.eq_of_toNat_eq; simpa [callBulk, arg] using hnr
    exact {P}_main12 s0 h h_nr h_r h_nowrap
  · have h_nr : read_mem_bytes 8 (r (StateField.GPR 31#5) s0 + 8#64) s0 = 14#64 := by
      apply BitVec.eq_of_toNat_eq; simpa [callBulk, arg] using hnr
    exact {P}_main14 s0 h h_nr h_r h_nowrap

end {ns}""")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
