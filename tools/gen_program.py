#!/usr/bin/env python3
"""Generate a Lean `Program` from one function of a Go arm64 binary.

Usage: gen_program.py <binary> <go-symbol> <lean-namespace> <lean-name> <out.lean>

Reads the function with `go tool objdump` (Go syntax, source lines, encodings)
and `llvm-objdump` (Arm syntax), places it at address 0, drops the alignment
padding after the last instruction, and writes

    def <lean-name> : Program := def_program [(0x0#64, 0x...#32), ...]

with both disassemblies as comments and the SHA-256 of the code bytes. The
generator only proposes text: the proofs are about the words in the Lean file,
run in the LNSym model.
"""
import hashlib
import re
import subprocess
import sys


def go_objdump(binary, sym):
    out = subprocess.run(
        ["go", "tool", "objdump", "-s", "^" + re.escape(sym) + "$", binary],
        check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.splitlines():
        m = re.match(r"\s+(\S+:\d+)\s+0x([0-9a-f]+)\s+([0-9a-f]{8})\s+(.*?)\s*$", line)
        if m:
            rows.append((m.group(1), int(m.group(2), 16), int(m.group(3), 16), m.group(4)))
    if not rows:
        sys.exit(f"symbol {sym} not found by go tool objdump")
    return rows


def llvm_objdump(binary, sym):
    out = subprocess.run(
        ["llvm-objdump", "-d", "--no-show-raw-insn", f"--disassemble-symbols={sym}", binary],
        check=True, capture_output=True, text=True).stdout
    asm = {}
    for line in out.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+(.*?)\s*$", line)
        if m:
            text = re.sub(r"\s+<[^>]*>", "", m.group(2)).replace("\t", " ")
            asm[int(m.group(1), 16)] = text
    return asm


def main():
    binary, sym, ns, name, out_path = sys.argv[1:6]
    rows = go_objdump(binary, sym)
    # Alignment padding after the last instruction decodes as `?` (word 0).
    while rows and rows[-1][2] == 0 and rows[-1][3] in ("?", "UNDEF", ""):
        rows.pop()
    base = rows[0][1]
    arm = llvm_objdump(binary, sym)
    code = b"".join(w.to_bytes(4, "little") for (_, _, w, _) in rows)
    sha = hashlib.sha256(code).hexdigest()
    go_version = subprocess.run(["go", "version"], check=True, capture_output=True,
                                text=True).stdout.strip()
    lines = []
    lines.append(f"/- Generated by tools/gen_program.py; do not edit.")
    lines.append(f"   Source: {sym} ({rows[0][0].split(':')[0]}), built by {go_version}, GOARCH=arm64.")
    lines.append(f"   {len(rows)} instructions, placed at address 0.")
    lines.append(f"   SHA-256 of the code bytes: {sha} -/")
    lines.append("import Arm.State")
    lines.append("")
    lines.append(f"namespace {ns}")
    lines.append("")
    lines.append("set_option maxRecDepth 100000 in")
    lines.append(f"/-- `{sym}`, {len(rows)} instructions at address 0. -/")
    lines.append(f"def {name} : Program :=")
    lines.append("  def_program")
    for i, (src, addr, word, goasm) in enumerate(rows):
        off = addr - base
        open_ = "  [" if i == 0 else "   "
        close = "]" if i == len(rows) - 1 else ","
        a = arm.get(addr, "?")
        lines.append(f"{open_}(0x{off:x}#64, 0x{word:08x}#32){close}  -- {a:<40} | {goasm} ({src})")
    lines.append("")
    lines.append(f"/-- Number of instructions in `{name}`. -/")
    lines.append(f"def {name}Length : Nat := {len(rows)}")
    lines.append("")
    lines.append(f"end {ns}")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out_path}: {len(rows)} instructions, sha256 {sha}")


if __name__ == "__main__":
    main()
