//go:build ignore

// gen_variants writes ctr_arm64_exp.s: variants of the bulk functions of
// ctr_arm64_gen.go that differ only in the tail groups (8, 4, 2, 1 blocks).
// The 12-block loop is the same in every variant.
package main

import (
	"fmt"
	"io"
	"os"
	"strings"
)

const (
	bulkBlocks = 12
	bulkKeyEnd = bulkBlocks + 14
	bulkStage  = bulkKeyEnd + 1
	bulkCtr    = bulkStage + 2
	bulkOne    = bulkCtr + 1
	bulkTwo    = bulkOne + 1
)

type variant struct {
	name  string
	eor3  bool
	tail  string // "pairs" (as in the CL), "ld4" (one LD1 of up to 4 free registers after the rounds), "pre" (src loaded before the rounds into free registers)
	align int    // PCALIGN before each skip label (0: none)
}

func main() {
	w := os.Stdout
	fmt.Fprint(w, "// Code generated by gen_variants.go. DO NOT EDIT.\n\n//go:build !purego\n\n#include \"textflag.h\"\n\n")
	fmt.Fprint(w, "#define NR R9\n#define XK R10\n#define DST R11\n#define SRC R12\n#define IV_LOW_LE R16\n#define IV_HIGH_LE R17\n")
	for _, v := range []variant{
		{"ctrBulkPairs", false, "pairs", 0},
		{"ctrBulkLd4", false, "ld4", 0},
		{"ctrBulkPre", false, "pre", 0},
		{"ctrBulkAlign", false, "pairs", 16},
		{"ctrBulkE3Pairs", true, "pairs", 0},
		{"ctrBulkE3Ld4", true, "ld4", 0},
		{"ctrBulkE3Pre", true, "pre", 0},
	} {
		genBulk(w, v)
	}
}

func genBulk(w io.Writer, vr variant) {
	p := func(format string, args ...any) { fmt.Fprintf(w, format+"\n", args...) }
	v := func(i int) string { return fmt.Sprintf("V%d.B16", i) }
	key := func(nr, k int) int { return bulkKeyEnd - nr + k }
	name := vr.name
	lbl := func(s string, args ...any) string { return name + "_" + fmt.Sprintf(s, args...) }

	counters := func(b int) {
		if b < 3 {
			for i := range b {
				p("\tVREV64 V%d.B16, %s", bulkCtr, v(i))
				p("\tVADD V%d.D2, V%d.D2, V%d.D2", bulkOne, bulkCtr, bulkCtr)
			}
			return
		}
		p("\tVADD V%d.D2, V%d.D2, V1.D2", bulkOne, bulkCtr)
		p("\tVADD V%d.D2, V%d.D2, V2.D2", bulkTwo, bulkCtr)
		p("\tVREV64 V%d.B16, V0.B16", bulkCtr)
		for k := 3; k < b; k++ {
			p("\tVADD V%d.D2, V%d.D2, V%d.D2", bulkTwo, k-2, k)
		}
		p("\tVADD V%d.D2, V%d.D2, V%d.D2", bulkTwo, b-2, bulkCtr)
		for k := 1; k < b; k++ {
			p("\tVREV64 %s, %s", v(k), v(k))
		}
	}

	rounds := func(nr, b int) {
		for k := range nr - 1 {
			for i := range b {
				p("\tAESE %s, %s", v(key(nr, k)), v(i))
				p("\tAESMC %s, %s", v(i), v(i))
			}
		}
		for i := range b {
			p("\tAESE %s, %s", v(key(nr, nr-1)), v(i))
		}
	}

	regList := func(first, n int) string {
		var r []string
		for i := range n {
			r = append(r, v(first+i))
		}
		return strings.Join(r, ", ")
	}

	// final XORs block i with the last key and with the plaintext in s.
	final := func(nr, i, s int) {
		last := key(nr, nr)
		if vr.eor3 {
			p("\tVEOR3 %s, %s, %s, %s", v(last), v(s), v(i), v(i))
		} else {
			p("\tVEOR %s, %s, %s", v(i), v(last), v(i))
			p("\tVEOR %s, %s, %s", v(i), v(s), v(i))
		}
	}

	// pairs: the CL's code.
	blocksPairs := func(nr, b int) {
		rounds(nr, b)
		var pending []int
		for g := 0; g < b; g += 2 {
			n := min(2, b-g)
			p("\tVLD1.P %d(SRC), [%s]", 16*n, regList(bulkStage, n))
			for j := range n {
				final(nr, g+j, bulkStage+j)
				pending = append(pending, g+j)
			}
			for len(pending) >= 4 || (g+n == b && len(pending) > 0) {
				k := min(4, len(pending))
				p("\tVST1.P [%s], %d(DST)", regList(pending[0], k), 16*k)
				pending = pending[k:]
			}
		}
	}

	// ld4: after the rounds, load up to 4 plaintext blocks at a time into the
	// free registers V(b)... (b <= 8 leaves at least 4 free below V12).
	blocksLd4 := func(nr, b int) {
		rounds(nr, b)
		f := b
		for g := 0; g < b; g += 4 {
			n := min(4, b-g)
			p("\tVLD1.P %d(SRC), [%s]", 16*n, regList(f, n))
			for j := range n {
				final(nr, g+j, f+j)
			}
			p("\tVST1.P [%s], %d(DST)", regList(g, n), 16*n)
		}
	}

	// pre: load the plaintext (up to 4 blocks) before the rounds; in the
	// plain variant also XOR it with the last key there, so one EOR follows
	// the last AESE. 8-block groups load their second half after the rounds.
	blocksPre := func(nr, b int) {
		last := key(nr, nr)
		f := b
		n0 := min(4, b)
		p("\tVLD1.P %d(SRC), [%s]", 16*n0, regList(f, n0))
		if !vr.eor3 {
			for j := range n0 {
				p("\tVEOR %s, %s, %s", v(f+j), v(last), v(f+j))
			}
		}
		rounds(nr, b)
		for j := range n0 {
			if vr.eor3 {
				p("\tVEOR3 %s, %s, %s, %s", v(last), v(f+j), v(j), v(j))
			} else {
				p("\tVEOR %s, %s, %s", v(j), v(f+j), v(j))
			}
		}
		p("\tVST1.P [%s], %d(DST)", regList(0, n0), 16*n0)
		for g := n0; g < b; g += 4 {
			n := min(4, b-g)
			p("\tVLD1.P %d(SRC), [%s]", 16*n, regList(f, n))
			for j := range n {
				final(nr, g+j, f+j)
			}
			p("\tVST1.P [%s], %d(DST)", regList(g, n), 16*n)
		}
	}

	p("")
	p("// func %s(nr int, xk *[60]uint32, dst, src *byte, n, r int, ivlo, ivhi uint64)", name)
	p("TEXT ·%s(SB), NOSPLIT, $0", name)
	p("\tMOVD nr+0(FP), NR")
	p("\tMOVD xk+8(FP), XK")
	p("\tMOVD dst+16(FP), DST")
	p("\tMOVD src+24(FP), SRC")
	p("\tMOVD n+32(FP), R13")
	p("\tMOVD r+40(FP), R15")
	p("\tMOVD ivlo+48(FP), IV_LOW_LE")
	p("\tMOVD ivhi+56(FP), IV_HIGH_LE")
	p("\tVMOV IV_HIGH_LE, V%d.D[0]", bulkCtr)
	p("\tVMOV IV_LOW_LE, V%d.D[1]", bulkCtr)
	p("\tVEOR V%d.B16, V%d.B16, V%d.B16", bulkOne, bulkOne, bulkOne)
	p("\tMOVD $1, R14")
	p("\tVMOV R14, V%d.D[1]", bulkOne)
	p("\tVADD V%d.D2, V%d.D2, V%d.D2", bulkOne, bulkOne, bulkTwo)
	p("\tCMP $12, NR")
	p("\tBLT %s", lbl("nr10"))
	p("\tBEQ %s", lbl("nr12"))
	for _, nr := range []int{14, 12, 10} {
		p("%s:", lbl("nr%d", nr))
		regs := make([]int, 0, nr+1)
		for k := range nr + 1 {
			regs = append(regs, key(nr, k))
		}
		for len(regs) > 0 {
			k := min(4, len(regs))
			var names []string
			for _, r := range regs[:k] {
				names = append(names, v(r))
			}
			p("\tVLD1.P %d(XK), [%s]", 16*k, strings.Join(names, ", "))
			regs = regs[k:]
		}
		p("\tCBZ R13, %s", lbl("tail%d", nr))
		p("%s:", lbl("loop%d", nr))
		counters(bulkBlocks)
		blocksPairs(nr, bulkBlocks)
		p("\tSUB $1, R13, R13")
		p("\tCBNZ R13, %s", lbl("loop%d", nr))
		p("%s:", lbl("tail%d", nr))
		for _, b := range []int{8, 4, 2, 1} {
			p("\tAND $%d, R15, R16", b)
			p("\tCBZ R16, %s", lbl("skip%d_%d", nr, b))
			counters(b)
			switch vr.tail {
			case "pairs":
				blocksPairs(nr, b)
			case "ld4":
				blocksLd4(nr, b)
			case "pre":
				blocksPre(nr, b)
			default:
				panic(vr.tail)
			}
			if vr.align > 0 {
				p("\tPCALIGN $%d", vr.align)
			}
			p("%s:", lbl("skip%d_%d", nr, b))
		}
		p("\tRET")
	}
}
