#!/usr/bin/env python3
"""Write AesCtrX86/Layout.lean and AesCtrX86/Blocks.lean from the output of
dis2kraken.py.

Usage: gen_lean.py <dis2kraken out dir> <Layout.lean> <Blocks.lean>

The layout places every directive of `prog` (the parsed functions, in address
order, then the data) at its address in the linked binary: labels take no
space, each instruction takes its length, and empty padding directives fill
the gaps between the functions and up to the data symbols.
"""
import sys

out, dest, dest_blocks = sys.argv[1:4]
funcs = []   # (name, address, size)
for line in open(out + "/funcs.txt"):
    name, addr, size = line.split()
    funcs.append((name, int(addr, 16), int(size, 16)))
data = {}
for line in open(out + "/data.txt"):
    name, addr, hexbytes = line.split()
    data[name] = (int(addr, 16), bytes.fromhex(hexbytes))

DOC = {
    "ctr1": "`ctrBlocks1Asm`",
    "ctr2": "`ctrBlocks2Asm`",
    "ctr4": "`ctrBlocks4Asm`",
    "ctr8": "`ctrBlocks8Asm`",
    "bulk": "`ctrBlocksBulkAsm`",
}

# Basic blocks: a new block starts at every label (jump target) and at the
# start of every function. Each block: address, asm lines, sizes, and the
# size of the padding after it (the last block of a function before the next
# one), or 0.
blocks = []
sizes = []          # the sizes of the directives of all functions, in order
for k, (name, faddr, fsize) in enumerate(funcs):
    lay = [l.split() for l in open("%s/%s.layout" % (out, name))]
    asm = [l.rstrip("\n") for l in open("%s/%s.S" % (out, name)) if l.strip()]
    li = 0
    first = True
    for f in lay:
        addr, n = int(f[0], 16), int(f[1])
        lines, szs = [], []
        if len(f) == 3:
            assert asm[li] == f[2] + ":", (asm[li], f)
            lines.append(asm[li]); szs.append(0); li += 1
        lines.append(asm[li]); szs.append(n); li += 1
        if len(f) == 3 or first:
            blocks.append([addr, lines, szs, 0])
            first = False
        else:
            blocks[-1][1].extend(lines); blocks[-1][2].extend(szs)
        sizes.extend(szs)
    assert li == len(asm)
    if k + 1 < len(funcs):
        gap = funcs[k + 1][1] - (faddr + fsize)
        assert gap > 0, "no padding between %s and the next function" % name
        blocks[-1][3] = gap
        sizes.append(gap)

start = funcs[0][1]
end = funcs[-1][1] + funcs[-1][2]

def blist(bs):
    return "⟨#[" + ", ".join("0x%02x" % b for b in bs) + "]⟩"

directives = []   # (lean text, size)
pos = end
def pad_to(addr):
    global pos
    assert addr >= pos
    directives.append((".byteArray ⟨#[]⟩", addr - pos))
    pos = addr
a, bs = data["bswapMask"]
pad_to(a)
directives.append(('.label "bswapMask"', 0))
directives.append((".byteArray " + blist(bs), 16)); pos += 16
a, bs = data["ctrOffsets"]
pad_to(a)
for k in range(len(bs) // 16):
    directives.append(('.label "ctrOffsets_%d"' % k, 0))
    directives.append((".byteArray " + blist(bs[16*k:16*k+16]), 16)); pos += 16

all_sizes = sizes + [sz for _, sz in directives]

def tree(xs, lo, hi, ind):
    """`xs[i]` for `lo <= i < hi`, as nested `if i < mid`."""
    if hi - lo == 1:
        return str(xs[lo])
    mid = (lo + hi) // 2
    return "if i < %d then\n%s  %s\n%selse\n%s  %s" % (
        mid, ind, tree(xs, lo, mid, ind + "  "), ind, ind, tree(xs, mid, hi, ind + "  "))

with open(dest, "w") as f:
    f.write("""/-
Generated by gen_lean.py from the linked test binary: do not edit.

`code_<f>` is function `<f>` as Kraken parses it, `data` the constants the
functions read, at the addresses where the linker put them, and `layout`
places every directive at its address in the binary.
-/
import Kraken.X64.Parser
import Kraken.X64.Semantics

open Kraken.X64.Parser

namespace AesCtrX86

""")
    for name, faddr, fsize in funcs:
        f.write("/-- %s, from the disassembly of the linked binary. -/\n" % DOC[name])
        f.write("def code_%s : Program := parseFile(\"asm/%s.S\")\n\n" % (name, name))
        f.write("/-- The address of %s in the binary. -/\n" % DOC[name])
        f.write("def entry_%s : Int64 := %#x\n\n" % (name, faddr))
    f.write("""/-- The data the functions read: `bswapMask` and the entries of `ctrOffsets`,
with the empty directives that pad the layout up to their addresses. -/
def data : Program := [
""")
    f.write(",\n".join("  " + d for d, _ in directives))
    f.write("]\n\n")
    parts = []
    for k, (name, _, _) in enumerate(funcs):
        parts.append("code_%s" % name)
        if k + 1 < len(funcs):
            parts.append("[.byteArray ⟨#[]⟩]")
    f.write("""/-- The functions in address order, with an empty directive for the padding
between two functions, then the data. -/
def prog : Program :=
  %s ++ data

/-- The size in the binary of directive `i` of `prog`, as a balanced search
on `i`, so that the kernel finds each size in a few comparisons (an array
lookup takes it time and memory linear in `i`). -/
def size (i : Nat) : Nat :=
  %s

/-- The address of the first function in the binary. -/
def start : Int64 := %#x

instance layout : Layout := { start := start, size := size }
""" % (" ++\n    ".join(parts), tree(all_sizes, 0, len(all_sizes), "  "), start))
    f.write("""

/-! The same program, split into basic blocks (a block starts at every label
and at the start of every function), each directive paired with its size.
The last block of a function before another one ends with the padding. -/

""")
    for addr, lines, szs, gap in blocks:
        pad = " ++ [(.byteArray ⟨#[]⟩, %d)]" % gap if gap else ""
        f.write("def blk_%x : List (Directive × Nat) := List.zip (parse(\"\n%s\")) [%s]%s\n\n"
                % (addr, "\n".join(lines), ", ".join(map(str, szs)), pad))
    f.write("def blkData : List (Directive × Nat) := List.zip data [%s]\n\n"
            % ", ".join(str(sz) for _, sz in directives))
    f.write("/-- The executable: the directives of `prog` with their sizes, from `start`. -/\n")
    f.write("def exe : Executable :=\n  (start, %s ++ blkData)\n\n" %
            " ++ ".join("blk_%x" % b[0] for b in blocks))
    f.write("""/-- `exe` is `prog`, laid out as in the binary. -/
theorem layout_prog : layout prog = exe := by
  show (start, prog.mapIdx (fun i d => (d, size i))) = exe
  rw [List.mapIdx_eq_zipIdx_map]
  decide +kernel

end AesCtrX86
""")
names = ["blk_%x" % b[0] for b in blocks] + ["blkData"]
with open(dest_blocks, "w") as f:
    f.write("""/-
Generated by gen_lean.py: do not edit.

For every block of `exe`, the directives that run from its address, and the
address of every label, checked by the kernel.
-/
import AesCtrX86.WithAddrs

namespace AesCtrX86

""")
    for k, (a, lines, _, _) in enumerate(blocks):
        f.write("theorem from_%x : exe.directivesFromAddress 0x%x =\n    %s := by\n"
                "  simp only [Kraken.Executable.directivesFromAddress, exe, withAddresses_eq]\n"
                "  decide +kernel\n\n" % (a, a, " ++ ".join(names[k:])))
        if lines[0].endswith(":"):
            f.write("theorem label_%x : (Executable.labels exe).label \"%s\" = 0x%x := by\n"
                    "  unfold Executable.labels\n  simp only [exe, withAddresses_eq]\n  decide +kernel\n\n"
                    % (a, lines[0][:-1], a))
    # From each block, the block runs, then whatever runs from the next one.
    for k, (a, lines, _, _) in enumerate(blocks):
        if k + 1 < len(blocks):
            nxt = blocks[k + 1][0]
            f.write("theorem next_%x : exe.directivesFromAddress 0x%x =\n"
                    "    blk_%x ++ exe.directivesFromAddress 0x%x := by\n"
                    "  rw [from_%x, from_%x]\n  simp only [List.append_assoc]\n\n"
                    % (a, a, a, nxt, a, nxt))
        else:
            f.write("theorem next_%x : exe.directivesFromAddress 0x%x = blk_%x ++ blkData :=\n"
                    "  from_%x\n\n" % (a, a, a, a))
    f.write("end AesCtrX86\n")
print("%d code directives, %d blocks, %d data directives" % (len(sizes), len(blocks), len(directives)))
